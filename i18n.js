  const LANGS = { de, en, fr, it, pl, es, nl, cs };

  let current = DEFAULT_LANG;

  // t('key') -> translated text.
  // t('key', v1) / t('key', [v1, v2]) -> replaces each %s in order.
  // Missing keys fall back to the German catalog, then to the key itself,
  // so a partial catalog never breaks the UI.
  function t(key, args) {
    const cat = LANGS[current] || LANGS[DEFAULT_LANG];
    let str = (key in cat) ? cat[key]
            : (key in LANGS[DEFAULT_LANG]) ? LANGS[DEFAULT_LANG][key]
            : key;
    if (args !== undefined) {
      const vals = Array.isArray(args) ? args : [args];
      vals.forEach(v => { str = str.replace('%s', String(v)); });
    }
    return str;
  }

  function setLang(code) {
    if (LANGS[code]) current = code;
    return current;
  }

  function getLang() {
    return current;
  }

  // Pick the initial language: explicit argument, then persisted choice
  // (localStorage), then browser language, then default.
  function detectLang(preferred, storage) {
    if (preferred && LANGS[preferred]) return preferred;
    try {
      if (storage) {
        const saved = JSON.parse(storage.getItem('kanban-lang:v1'));
        if (saved && LANGS[saved]) return saved;
      }
    } catch (e) { /* ignore */ }
    for (const l of navigator.languages || [navigator.language]) {
      const base = String(l).slice(0, 2).toLowerCase();
      if (LANGS[base]) return base;
    }
    return DEFAULT_LANG;
  }

  function persistLang(code, storage) {
    if (!LANGS[code]) return;
    try { if (storage) storage.setItem('kanban-lang:v1', JSON.stringify(code)); } catch (e) { /* ignore */ }
  }

